name = "Deep"
print(len(name)) # This will print the length of the string 

print(name.endswith("ep")) # This will check if the string ends with "ep" and return True or False

print(name.startswith("De")) # This will check if the string starts with "De" and return True or False

print(name.capitalize()) #This will convert the 1st charecter of the string into capital.

print(name.find("p")) # It finds the charecter and give the position of the charecter in string.

print(name.replace("Deep", "Deep doshi")) #It is a replace function which is replace a charecter into a new charecter

print(name.upper()) #This will convert the given string into uppercase.

print(name.lower()) #This will convert the given string into lowercase.