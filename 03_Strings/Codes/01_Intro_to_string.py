#This is a string variable
name = "Deep" 
print(name)    

#This is a string slicing operation, it will take the first character of the string "Deep" and assign it to the variable nameshort
nameshort = name[0] 
print(nameshort) 

#This is a string slicing operation, it will take the first two characters of the string "Deep" and assign it to the variable short
short = name[0:2]
